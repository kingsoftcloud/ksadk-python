"""Render the reviewed pnpm dependency-resolution policy without host effects."""

from __future__ import annotations

import json
from collections.abc import Mapping


def dependency_policy(version: str, vendor_versions: Mapping[str, str]) -> str:
    """Keep the official synchronized DSH packages on the reviewed release.

    The published CLI uses caret dependencies even for release candidates.
    Pinning only the CLI would allow its Core/client packages to resolve to a
    later candidate. The pnpm hook changes resolution, not upstream source.
    """

    return (
        "// Generated by KsADK; the complete DSH release is an atomic dependency.\n"
        f"const version = {json.dumps(version)};\n"
        f"const vendorVersions = {json.dumps(vendor_versions, sort_keys=True)};\n"
        "module.exports = { hooks: { readPackage(pkg) {\n"
        "  for (const field of ['dependencies', 'optionalDependencies', 'peerDependencies']) {\n"
        "    for (const name of Object.keys(pkg[field] || {})) {\n"
        "      const target = name === '@deepseek-ai/dsh' || name.startsWith('@deepseek-ai/dsh-')\n"
        "        ? version : vendorVersions[name];\n"
        "      if (target !== undefined) {\n"
        "        const requested = pkg[field][name];\n"
        "        if (!/^[~^<>=*xX0-9][0-9A-Za-z.*+~^<>=| -]*$/.test(requested)) {\n"
        "          throw new Error('DSH dependencies require a release version: ' + name);\n"
        "        }\n"
        "        if (/^\\d+\\.\\d+\\.\\d+(?:-[0-9A-Za-z.-]+)?$/.test(requested)\n"
        "            && requested !== target) {\n"
        "          throw new Error('DSH dependency version conflicts with host: ' + name);\n"
        "        }\n"
        "        pkg[field][name] = target;\n"
        "      }\n"
        "    }\n"
        "  }\n"
        "  return pkg;\n"
        "} } };\n"
    )
