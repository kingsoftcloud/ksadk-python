import { spawnSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync, mkdirSync } from 'node:fs';
import { cpus, platform, release, arch, totalmem } from 'node:os';
import { performance } from 'node:perf_hooks';
import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { GroupReducer, decodeGroupSnapshot } from '@kingsoftcloud/ksadk-web/teams';
import { InvocationTree } from '@kingsoftcloud/ksadk-web/teams/execution';
const studio = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fixture = spawnSync('uv', ['run', '--no-sync', 'python', resolve(studio, 'scripts/teams-domain-fixture.py')], { cwd: resolve(studio, '../../..'), encoding: 'utf8' });
assert.equal(fixture.status, 0, fixture.stderr);
const data = JSON.parse(fixture.stdout);
const snapshot = data.stages[0].snapshot;
const sourceMember = snapshot.members[0];
snapshot.members = Array.from({ length: 8 }, (_, i) => ({ ...sourceMember, memberId: `perf-member-${i}`, name: `Reference member ${i}`, role: i ? 'member' : 'leader', sessionId: `perf-session-${i}` }));
snapshot.group.leaderMemberId = snapshot.members[0].memberId;
snapshot.watermark = 0;
snapshot.messages = [];
const origin = data.stages.at(-1).snapshot.messages[0];
const events = Array.from({ length: 10_000 }, (_, i) => ({ apiVersion: snapshot.apiVersion, eventId: `perf-event-${i}`, groupId: snapshot.group.groupId, groupSeq: i + 1, type: 'message.created', createdAt: origin.createdAt, payload: { message: { ...origin, messageId: `perf-message-${i}`, sourceRefs: [], parts: [{ kind: 'text', text: 'identical public text' }] } } }));
const start = performance.now();
const reducer = new GroupReducer(decodeGroupSnapshot(snapshot));
for (const event of events) reducer.apply(event);
const replayMs = performance.now() - start;
for (const event of events) assert.equal(reducer.apply(event), false);
assert.equal(reducer.snapshot().watermark, 10_000);
assert.equal(reducer.snapshot().messages.length, 10_000);
assert.deepEqual(reducer.snapshot().messages.map(row => row.messageId), events.map(row => row.payload.message.messageId));
const execution = { groupId: snapshot.group.groupId, teamRunId: 'perf-round', watermark: 10_000, nodes: Array.from({ length: 200 }, (_, i) => ({ nodeId: `perf-node-${i}`, kind: 'run', title: `Execution ${i}`, status: 'succeeded', memberId: snapshot.members[i % 8].memberId })), edges: [] };
const renderStart = performance.now();
const html = renderToStaticMarkup(React.createElement(InvocationTree, { execution, onSelect: () => {} }));
const render200NodesMs = performance.now() - renderStart;
for (let i=0;i<200;i++) assert.ok(html.includes(`Execution ${i}<`), `missing node ${i}`);
const report = { measuredAt: new Date().toISOString(), environment: { platform: platform(), release: release(), arch: arch(), cpu: cpus()[0].model, logicalCpus: cpus().length, memoryGiB: Math.round(totalmem()/2**30), node: process.version }, transport: 'Synthetic fixed events built from actual Python domain schema; in-process reducer and React SSR, not a live transport benchmark', members: 8, visibleNodes: 200, events: 10000, replayMs: +replayMs.toFixed(2), render200NodesMs: +render200NodesMs.toFixed(2), assertions: ['all 10000 same-text unique messages retained in exact order', 'replaying all events adds zero duplicates', 'watermark equals 10000', 'all 200 execution nodes rendered'] };
mkdirSync(resolve(studio, 'output'), { recursive: true });
writeFileSync(resolve(studio, 'output/teams-performance.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
