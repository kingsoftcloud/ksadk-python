from __future__ import annotations

import asyncio
import sqlite3

import pytest

from ksadk.a2a.task_event_dispatcher import A2ATaskEventDispatcher
from ksadk.a2a.task_event_outbox import (
    PostgresA2ATaskEventOutbox,
    SQLiteA2ATaskEventOutbox,
)


class _RecordingConnection:
    def __init__(self) -> None:
        self.statements: list[str] = []

    async def execute(self, statement) -> None:  # noqa: ANN001
        self.statements.append(str(statement))


class _RecordingBegin:
    def __init__(self, connection: _RecordingConnection) -> None:
        self.connection = connection

    async def __aenter__(self) -> _RecordingConnection:
        return self.connection

    async def __aexit__(self, *_args) -> None:
        return None


class _RecordingEngine:
    def __init__(self) -> None:
        self.connection = _RecordingConnection()

    def begin(self) -> _RecordingBegin:
        return _RecordingBegin(self.connection)


@pytest.mark.asyncio
async def test_postgres_outbox_schema_supports_postgres_96() -> None:
    engine = _RecordingEngine()
    await PostgresA2ATaskEventOutbox(engine).initialize()  # type: ignore[arg-type]

    schema = "\n".join(engine.connection.statements)
    assert "sequence BIGSERIAL PRIMARY KEY" in schema
    assert "ksadk_a2a_task_event_dead_letters" in schema
    assert "GENERATED BY DEFAULT AS IDENTITY" not in schema


class _TaskSink:
    def __init__(self) -> None:
        self.available = False
        self.calls: list[dict] = []

    async def append_task_events(self, *, platform_task_id, events):  # noqa: ANN001
        if not self.available:
            raise RuntimeError("task sink unavailable")
        self.calls.append({"platform_task_id": platform_task_id, "events": events})
        return {"AcceptedCount": len(events)}


class _HangingTaskSink:
    async def append_task_events(self, *, platform_task_id, events):  # noqa: ANN001
        await asyncio.Event().wait()


class _PermanentTaskError(RuntimeError):
    error_code = "A2A_EVENT_REF_INVALID"


class _PoisonThenHealthyTaskSink:
    def __init__(self) -> None:
        self.calls: list[str] = []

    async def append_task_events(self, *, platform_task_id, events):  # noqa: ANN001
        _ = events
        self.calls.append(platform_task_id)
        if platform_task_id == "a2a-task-poison":
            raise _PermanentTaskError("invalid canonical event reference")
        return {"AcceptedCount": 1}


@pytest.mark.asyncio
async def test_dispatcher_replays_outbox_on_start_and_retries_in_background(tmp_path) -> None:
    outbox = SQLiteA2ATaskEventOutbox(tmp_path / "events.sqlite3")
    sink = _TaskSink()
    dispatcher = A2ATaskEventDispatcher(outbox, sink, retry_interval_seconds=0.01)

    await dispatcher.start()
    await dispatcher.enqueue(
        platform_task_id="a2a-task-00000000000040008000000000000004",
        events=[{"SourceEventId": "event-1", "EventKind": "status"}],
    )
    assert len(await outbox.pending()) == 1
    for _ in range(100):
        if dispatcher.degraded:
            break
        await asyncio.sleep(0.01)
    assert dispatcher.degraded is True

    sink.available = True
    for _ in range(100):
        if not await outbox.pending():
            break
        await asyncio.sleep(0.01)
    await dispatcher.stop(flush_timeout_seconds=0.1)

    assert await outbox.pending() == []
    assert sink.calls[0]["events"][0]["SourceEventId"] == "event-1"


@pytest.mark.asyncio
async def test_dispatcher_preserves_sqlite_enqueue_order(tmp_path) -> None:
    outbox = SQLiteA2ATaskEventOutbox(tmp_path / "events.sqlite3")
    for number in range(10):
        await outbox.enqueue(
            platform_task_id="a2a-task-00000000000040008000000000000004",
            events=[{"SourceEventId": f"event-{number}", "EventKind": "status"}],
        )

    pending = await outbox.pending(limit=20)

    assert [batch.events[0]["SourceEventId"] for batch in pending] == [
        f"event-{number}" for number in range(10)
    ]


@pytest.mark.asyncio
async def test_dispatcher_enqueue_does_not_wait_for_a_hanging_task_sink(tmp_path) -> None:
    outbox = SQLiteA2ATaskEventOutbox(tmp_path / "events.sqlite3")
    dispatcher = A2ATaskEventDispatcher(
        outbox,
        _HangingTaskSink(),
        retry_interval_seconds=0.01,
        task_sink_timeout_seconds=0.02,
    )
    await dispatcher.start()
    try:
        await asyncio.wait_for(
            dispatcher.enqueue(
                platform_task_id="a2a-task-00000000000040008000000000000004",
                events=[{"SourceEventId": "event-1", "EventKind": "status"}],
            ),
            timeout=0.1,
        )
        await asyncio.sleep(0.05)
        assert dispatcher.degraded is True
        assert len(await outbox.pending()) == 1
    finally:
        await dispatcher.stop(flush_timeout_seconds=0)


@pytest.mark.asyncio
async def test_dispatcher_dead_letters_permanent_head_and_drains_following_batch(tmp_path) -> None:
    path = tmp_path / "events.sqlite3"
    outbox = SQLiteA2ATaskEventOutbox(path)
    sink = _PoisonThenHealthyTaskSink()
    dispatcher = A2ATaskEventDispatcher(outbox, sink)
    await outbox.enqueue(
        platform_task_id="a2a-task-poison",
        events=[{"SourceEventId": "invalid-event", "EventKind": "status"}],
    )
    await outbox.enqueue(
        platform_task_id="a2a-task-healthy",
        events=[{"SourceEventId": "valid-event", "EventKind": "status"}],
    )

    delivered = await dispatcher.drain(raise_on_error=False)

    assert delivered == 1
    assert await outbox.pending() == []
    assert sink.calls == ["a2a-task-poison", "a2a-task-healthy"]
    with sqlite3.connect(path) as connection:
        dead_letter = connection.execute(
            """
            SELECT platform_task_id, attempt_count, last_error
            FROM a2a_task_event_dead_letters
            """
        ).fetchone()
    assert dead_letter == ("a2a-task-poison", 1, "A2A_EVENT_REF_INVALID")


@pytest.mark.asyncio
async def test_explicit_flush_reports_prior_background_dead_letter(tmp_path) -> None:
    outbox = SQLiteA2ATaskEventOutbox(tmp_path / "events.sqlite3")
    sink = _PoisonThenHealthyTaskSink()
    dispatcher = A2ATaskEventDispatcher(outbox, sink)
    await dispatcher.enqueue(platform_task_id="a2a-task-poison", events=[{"id": "bad"}])
    assert await dispatcher.drain(raise_on_error=False) == 0
    assert await outbox.pending() == []
    assert dispatcher.degraded
    assert dispatcher.last_error == "A2A_EVENT_REF_INVALID"
    with pytest.raises(RuntimeError, match="A2A_EVENT_REF_INVALID"):
        await dispatcher.drain(raise_on_error=True)
    # The failure remains visible but never blocks delivery of healthy work.
    await dispatcher.enqueue(platform_task_id="a2a-task-healthy", events=[{"id": "good"}])
    assert await dispatcher.drain(raise_on_error=False) == 1
    assert sink.calls == ["a2a-task-poison", "a2a-task-healthy"]
    assert dispatcher.degraded
    with pytest.raises(RuntimeError, match="A2A_EVENT_REF_INVALID"):
        await dispatcher.drain(raise_on_error=True)
